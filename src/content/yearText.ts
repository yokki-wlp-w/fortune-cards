export interface YearLine {
  /** 根拠の見出し */
  label: string
  text: string
  tone: 'good' | 'caution' | 'neutral'
}

/** 1年分の傾向を、根拠つきの文章にする */
export function describeYear(y: YearFortune): YearLine[] {
  const lines: YearLine[] = [
    { label: `通変星「${y.tsuhensei}」`, text: YEAR_TSUHEN_TEXT[y.tsuhensei], tone: 'neutral' },
    { label: `十二運「${y.juniun}」`, text: YEAR_JUNIUN_TEXT[y.juniun], tone: 'neutral' },
  ]
  for (const r of y.relations) {
    lines.push({
      label: `${POSITION_NOTE[r.position]}：${r.detail}`,
      text: `流年の支${RELATION_NOTE[r.relation]}`,
      tone: r.relation === 'rikugo' || r.relation === 'sango' ? 'good' : r.relation === 'same' ? 'neutral' : 'caution',
    })
  }
  if (y.kango) {
    lines.push({ label: '干合の年', text: '流年の天干が日干と「干合」します。人との縁や、協力関係が生まれやすい年とされます。', tone: 'good' })
  }
  if (y.kuubou) {
    lines.push({
      label: '空亡（天中殺）の年',
      text: '思いどおりに進みにくいとされる時期です。大きな決断は急がず、学びや整理、人のための活動にあてると過ごしやすいようです。',
      tone: 'caution',
    })
  }
  lines.push({
    label: `九星：${KYUSEI_NAMES[y.kyusei.center]}の年・本命星は${y.kyusei.palace}`,
    text: PALACE_TEXT[y.kyusei.palace],
    tone: 'neutral',
  })
  return lines
}
