/** 動物どうしの相性コメント（表示のみ・スコア対象外） */
export function animalPairNote(a: string, b: string): string {
  const ea = ANIMAL_TEXT[a].energy
  const eb = ANIMAL_TEXT[b].energy
  if (a === b) return '同じ動物タイプどうしです。感覚が近く、説明なしで通じる場面が多い傾向があります。似ているぶん、役割が重ならないよう分担を決めておくとよさそうです。'
  if (ea === eb) return 'エネルギーの出し方が近い組み合わせです。ペースが合いやすい一方、苦手な領域も似やすいので、補い合える第三者がいると安心です。'
  if (ea !== 'balanced' && eb !== 'balanced') return '前に出るタイプと、内側で力を蓄えるタイプの組み合わせです。ペースの違いを「役割の違い」として認め合うと、互いを補いやすくなります。'
  return '動き方に少し違いのある組み合わせです。相手のペースを先に確認しておくと、ほどよい刺激を与え合える関係になりやすいようです。'
}
